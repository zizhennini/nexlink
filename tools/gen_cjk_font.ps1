# gen_cjk_font.ps1 - generate a minimal 16x16 CJK bitmap font from SimSun's
# embedded 16px bitmaps. Outputs:
#   main/display/cjk_font.h  (C table, 32 bytes per glyph)
#   tools/cjk_font.js        (same data for the OLED UI simulator)
# Chinese chars are built from code points so this script stays pure ASCII.

Add-Type -AssemblyName System.Drawing

$codes = @(
  0x72B6,0x6001,0x603B,0x89C8,   # zhuang tai zong lan
  0x4E32,0x53E3,0x76D1,0x89C6,   # chuan kou jian shi
  0x65E0,0x7EBF,0x5DF2,0x8FDE,0x63A5,  # wu xian yi lian jie
  0x70ED,0x70B9,0x6A21,0x5F0F,   # re dian mo shi
  0x672A,0x5173,0x95ED,          # wei guan bi
  0x63A2,0x9488,                 # tan zhen
  0x590D,0x4F4D,0x76EE,0x6807,   # fu wei mu biao
  0x9891,0x7387,0x5360,0x7A7A,   # pin lv zhan kong
  0x5F00,0x59CB,0x8F93,0x51FA,   # kai shi shu chu
  0x505C,0x6B62,                 # ting zhi
  0x5F53,0x524D,0x89D2,0x8272,   # dang qian jiao se
  0x5207,0x6362,0x4F1A,0x91CD,0x542F,  # qie huan hui zhong qi
  0x79D2,0x5206,0x65F6,0x5929,   # miao fen shi tian
  0x6587,0x672C,0x4E2D,          # wen ben zhong
  0x7B49,0x5F85,0x6570,0x636E,   # deng dai shu ju
  0x63A7,0x5236,                 # kong zhi
  0x6D4B,0x91CF,                 # ce liang
  0x540E,                        # hou
  0x4E3A,0x8BFB,0x53D6           # wei (as) du (read) qu (fetch)
)

$root = Split-Path -Parent $PSScriptRoot
$hPath  = Join-Path $root "main\display\cjk_font.h"
$jsPath = Join-Path $PSScriptRoot "cjk_font.js"

$bmp = New-Object System.Drawing.Bitmap 16,16
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.PageUnit = [System.Drawing.GraphicsUnit]::Pixel
$g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
# GdiCharSet 134 = GB2312, forces SimSun's embedded 16px bitmap (not outlines)
$font = New-Object System.Drawing.Font("SimSun", 16, [System.Drawing.FontStyle]::Regular,
                                       [System.Drawing.GraphicsUnit]::Pixel, 134)

$rect = New-Object System.Drawing.Rectangle 0,0,16,16
$glyphs = @()

foreach ($cp in $codes) {
    $g.Clear([System.Drawing.Color]::Black)
    $g.DrawString([string][char]$cp, $font, [System.Drawing.Brushes]::White, 0, 0)
    $ld = $bmp.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly,
                        [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $stride = $ld.Stride
    $raw = New-Object byte[] ($stride * 16)
    [System.Runtime.InteropServices.Marshal]::Copy($ld.Scan0, $raw, 0, $raw.Length)
    $bmp.UnlockBits($ld)

    # 1bpp row-major, 2 bytes per row, MSB left
    $bits = New-Object byte[] 32
    for ($y = 0; $y -lt 16; $y++) {
        $b0 = 0; $b1 = 0
        for ($x = 0; $x -lt 8; $x++) {
            $r = $raw[$y * $stride + $x * 4 + 2]
            if ($r -ge 128) { $b0 = $b0 -bor (1 -shl (7 - $x)) }
        }
        for ($x = 8; $x -lt 16; $x++) {
            $r = $raw[$y * $stride + $x * 4 + 2]
            if ($r -ge 128) { $b1 = $b1 -bor (1 -shl (15 - $x)) }
        }
        $bits[$y * 2] = $b0
        $bits[$y * 2 + 1] = $b1
    }
    $glyphs += ,@($cp, $bits)
}

$g.Dispose(); $bmp.Dispose()

function HexB($b) { return ("0x{0:X2}" -f $b) }

# ---- C header ----
$cl = New-Object System.Collections.Generic.List[string]
$cl.Add("/* Auto-generated by tools/gen_cjk_font.ps1 from SimSun 16px. Do not edit. */")
$cl.Add("#pragma once")
$cl.Add("#include <stdint.h>")
$cl.Add("")
$cl.Add("typedef struct { uint16_t cp; uint8_t d[32]; } cjk_glyph_t;")
$cl.Add("static const cjk_glyph_t cjk_table[] = {")
foreach ($g2 in $glyphs) {
    $cp = $g2[0]; $bits = $g2[1]
    $hex = ($bits | ForEach-Object { HexB $_ }) -join ","
    $cl.Add('    {0x' + ('{0:X4}' -f $cp) + ',{' + $hex + '}},')
}
$cl.Add("};")
$cl.Add("#define CJK_GLYPH_COUNT (sizeof(cjk_table)/sizeof(cjk_table[0]))")
[System.IO.File]::WriteAllText($hPath, ($cl -join "`r`n") + "`r`n",
    (New-Object System.Text.UTF8Encoding($false)))

# ---- JS (simulator) ----
$jl = New-Object System.Collections.Generic.List[string]
$jl.Add("// Auto-generated by tools/gen_cjk_font.ps1. SimSun 16px bitmaps.")
$jl.Add("var CJKFONT = {")
foreach ($g2 in $glyphs) {
    $ch = [string][char]$g2[0]
    $nums = ($g2[1] | ForEach-Object { "0x{0:X2}" -f $_ }) -join ","
    $jl.Add('  "' + $ch + '":[' + $nums + '],')
}
$jl.Add("};")
[System.IO.File]::WriteAllText($jsPath, ($jl -join "`r`n") + "`r`n",
    (New-Object System.Text.UTF8Encoding($false)))

Write-Host ("generated {0} glyphs -> {1}, {2}" -f $glyphs.Count, $hPath, $jsPath)
